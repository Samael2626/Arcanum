import 'package:flutter/foundation.dart';

import 'name_sources.dart';

/// Raiz historica de un nombre, en la escritura de su propia tradicion.
@immutable
class NameRoot {
  final String hebrew;
  final String transliteration;
  final String meaning;

  const NameRoot({
    required this.hebrew,
    required this.transliteration,
    required this.meaning,
  });
}

/// Ficha editorial verificable de un nombre.
///
/// Cuatro planos separados que nunca deben colapsarse entre si:
/// forma documentada, significado historico, tradicion y fuente, y
/// limite editorial. La lectura simbolica de ARCANUM vive fuera de aqui.
@immutable
class NameCatalogEntry {
  final String id;
  final String displayName;
  final List<String> variants;
  final NameTradition tradition;
  final String origin;
  final String meaning;
  final String etymology;
  final EvidenceLevel formEvidence;
  final EvidenceLevel meaningEvidence;

  /// Escritura hebrea atestiguada. Unico campo que habilita gematria
  /// historica; solo puede existir en fichas de tradicion hebrea.
  final String? hebrew;

  /// Escritura documentada en tradiciones no hebreas.
  final String? documentedForm;
  final String? documentedFormLabel;

  final String citation;
  final NameSource source;

  /// Enlace profundo opcional al lema exacto, cuando existe uno estable.
  final String? entryUrl;

  final String editorialLimit;
  final String? story;
  final List<NameRoot> traditionalRoots;
  final String? traditionalRootsLimit;

  const NameCatalogEntry({
    required this.id,
    required this.displayName,
    required this.variants,
    required this.tradition,
    required this.origin,
    required this.meaning,
    required this.etymology,
    required this.formEvidence,
    required this.meaningEvidence,
    this.hebrew,
    this.documentedForm,
    this.documentedFormLabel,
    required this.citation,
    required this.source,
    this.entryUrl,
    required this.editorialLimit,
    this.story,
    this.traditionalRoots = const [],
    this.traditionalRootsLimit,
  });

  bool get hasHistoricalHebrew => hebrew != null && hebrew!.isNotEmpty;

  String? get archiveForm => documentedForm ?? hebrew;

  String? get archiveFormLabel {
    if (archiveForm == null) return null;
    return documentedFormLabel ??
        switch (tradition) {
          NameTradition.hebrew => 'Forma hebrea documentada',
          NameTradition.greek => 'Forma griega documentada',
          NameTradition.latin => 'Forma latina documentada',
          NameTradition.germanic => 'Raíz germánica reconstruida',
          NameTradition.arabic => 'Forma árabe documentada',
        };
  }

  String get certainty =>
      'Forma: ${formEvidence.label}. Significado: ${meaningEvidence.label}.';

  String get sourceUrl => entryUrl ?? source.url;

  String get attribution => source.attribution;

  String get license => source.license;

  /// Texto de la ficha visible antes de abrir la nota de archivo.
  /// Nunca debe contener enlaces ni jerga de licencias.
  String get visibleProse =>
      [meaning, etymology, story, traditionalRootsLimit].nonNulls.join(' ');
}

