  static NameCatalogEntry? find(String value) {
    final key = _normalize(value);
    if (key.isEmpty) return null;
    for (final entry in entries) {
      if (_normalize(entry.displayName) == key ||
          entry.variants.any((variant) => _normalize(variant) == key)) {
        return entry;
      }
    }
    return null;
  }

  static Iterable<NameCatalogEntry> byTradition(NameTradition tradition) =>
      entries.where((entry) => entry.tradition == tradition);

  static String _normalize(String value) => value
      .trim()
      .toLowerCase()
      .replaceAll('á', 'a')
      .replaceAll('é', 'e')
      .replaceAll('í', 'i')
      .replaceAll('ó', 'o')
      .replaceAll('ú', 'u')
      .replaceAll('ü', 'u');
}
